def parse_search_plan(content: str, description: str) -> SearchPlan:
    try:
        raw = json.loads(content)
        if isinstance(raw, dict) and isinstance(raw.get("filters"), dict):
            raw["filters"] = generated_filters(raw["filters"], description)
        plan = SearchPlan.model_validate(raw)
    except (ValueError, ValidationError) as exc:
        raise LlmError("LLM returned an invalid search plan") from exc
    if re.search(r'[а-яё]', description, re.I):
        allowed = {word.casefold() for word in re.findall(r'[a-z]{3,}', description, re.I)}
        for term in [*plan.queries, *plan.must_have, *plan.exclude]:
            if any(word.casefold() not in allowed for word in re.findall(r'[a-z]{3,}', term, re.I)):
                raise LlmError('Модель вернула признаки или формулировки с посторонним английским текстом. Повторите составление плана.')
    return plan

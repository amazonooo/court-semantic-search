def parse_search_plan(content: str, description: str) -> SearchPlan:
    try:
        raw = json.loads(content)
        if isinstance(raw, dict) and isinstance(raw.get("filters"), dict):
            raw["filters"] = generated_filters(raw["filters"], description)
        plan = SearchPlan.model_validate(raw)
    except (ValueError, ValidationError) as exc:
        raise LlmError("LLM returned an invalid search plan") from exc
    if re.search(r'[а-яё]', description, re.I):
        allowed = {word.casefold() for word in re.findall(r'[a-z]{3,}', description, re.I)}
        for term in [*plan.queries, *plan.must_have, *plan.exclude]:
            if any(word.casefold() not in allowed for word in re.findall(r'[a-z]{3,}', term, re.I)):
                raise LlmError('Модель вернула признаки или формулировки с посторонним английским текстом. Повторите составление плана.')
    # A tax subject is a relationship to be assessed, not a literal search
    # phrase. Keep it even when the planner omits it from otherwise good facts.
    if re.search(r'налогов\w*\s+(?:спор|орган|инспекц)|по\s+налогов\w*\s+спор', description, re.I):
        has_subject = any(re.search(r'налогов\w*\s+(?:предмет|спор|орган|инспекц)|предмет.*налог|оспар.*налог', term, re.I)
                          for term in plan.must_have)
        if not has_subject:
            if len(plan.must_have) >= 10:
                raise LlmError('Модель пропустила налоговый предмет спора. Уточните или повторите составление плана.')
            plan.must_have.insert(0, 'Налоговый предмет спора по описанной операции')
    # Detect the specific role reversal reported by reviewers before spending
    # source calls. Do not silently replace a user-supplied editable plan.
    buyer_borrowed = re.search(r'компани[яи]-покупател\w*\s+привлек\w*\s+(?:за[её]м|кредит)', description, re.I)
    if buyer_borrowed and any(re.search(r'(?:купил|приобрел|приобрёл)\w*\s+компани\w*-за[её]мщик', term, re.I)
                             for term in [*plan.queries, *plan.must_have]):
        raise LlmError('Модель перепутала покупателя-заёмщика и приобретённую компанию. Повторите составление плана.')
    if any(re.search(r'налогов\w*\s+расход', term, re.I) for term in plan.must_have):
        raise LlmError('Модель использовала некорректное понятие «налоговые расходы». Повторите составление плана.')
    return plan
